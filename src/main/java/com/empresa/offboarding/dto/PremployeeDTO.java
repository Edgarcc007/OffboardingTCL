package com.empresa.offboarding.dto;

public class PremployeeDTO {
    private String employeeCode;
    private int employeeNum;
    private String employeeName;
    private String deptCode;
    private String deptName;
    private String areaCode;
    private String areaName;
    private String superCode;
    private String superName;
    private String turnCode;
    private String turnName;
    private String rollCode;
    private String rollName;

    public String getEmployeeCode()       { return employeeCode; }
    public void setEmployeeCode(String v) { this.employeeCode = v; }

    public int getEmployeeNum()           { return employeeNum; }
    public void setEmployeeNum(int v)     { this.employeeNum = v; }

    public String getEmployeeName()       { return employeeName; }
    public void setEmployeeName(String v) { this.employeeName = v; }

    public String getDeptCode()           { return deptCode; }
    public void setDeptCode(String v)     { this.deptCode = v; }

    public String getDeptName()           { return deptName; }
    public void setDeptName(String v)     { this.deptName = v; }

    public String getAreaCode()           { return areaCode; }
    public void setAreaCode(String v)     { this.areaCode = v; }

    public String getAreaName()           { return areaName; }
    public void setAreaName(String v)     { this.areaName = v; }

    public String getSuperCode()          { return superCode; }
    public void setSuperCode(String v)    { this.superCode = v; }

    public String getSuperName()          { return superName; }
    public void setSuperName(String v)    { this.superName = v; }

    public String getTurnCode()           { return turnCode; }
    public void setTurnCode(String v)     { this.turnCode = v; }

    public String getTurnName()           { return turnName; }
    public void setTurnName(String v)     { this.turnName = v; }

    public String getRollCode()           { return rollCode; }
    public void setRollCode(String v)     { this.rollCode = v; }

    public String getRollName()           { return rollName; }
    public void setRollName(String v)     { this.rollName = v; }
}
